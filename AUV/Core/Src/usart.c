#define IMU_DMA_RX_BUF_LEN 128U
static uint8_t imu_dma_rx_buf[IMU_DMA_RX_BUF_LEN];
#define RC_DMA_RX_BUF_LEN 64U
static uint8_t rc_dma_rx_buf[RC_DMA_RX_BUF_LEN];

void USART1_Receive_DMA_Init(void)
{
  HAL_UART_DMAStop(&huart1);

  if (HAL_UARTEx_ReceiveToIdle_DMA(&huart1, imu_dma_rx_buf,
                                   IMU_DMA_RX_BUF_LEN) != HAL_OK) {
    return;
  }

  /* 空闲中断用于帧结束；不需要半满 DMA 中断。 */
  __HAL_DMA_DISABLE_IT(huart1.hdmarx, DMA_IT_HT);
}

void USART2_Receive_DMA_Init(void)
{
	HAL_UART_DMAStop(&huart2);

	if (HAL_UARTEx_ReceiveToIdle_DMA(&huart2, rc_dma_rx_buf,
	                                 RC_DMA_RX_BUF_LEN) != HAL_OK)
	{
		return;
	}

	/* 只使用 UART 空闲/满缓冲事件，不使用 DMA 半传输事件。 */
	__HAL_DMA_DISABLE_IT(huart2.hdmarx, DMA_IT_HT);
}
/*
 * USART1 在检测到空闲时进入这里。size 是本次实际收到的字节数，
 * 不能把 DMA 缓冲区直接当作一帧；逐字节送入状态机以自动重新同步
 * 0x59 0x53 帧头，并跨 DMA 分块保留未收齐的帧。
 */
void HAL_UARTEx_RxEventCallback(UART_HandleTypeDef *huart, uint16_t size)
{
	if ((huart == NULL) || (size == 0U)) {
    return;
  }

	if (huart->Instance == USART1)
	{
		if (size > IMU_DMA_RX_BUF_LEN)
		{
			USART1_Receive_DMA_Init();
			return;
		}
    if ( PID_Cal_Flag == 0)
    {
      for (uint16_t i = 0U; i < size; i++)
		  {
			  h30_data_callback(imu_dma_rx_buf[i]);
        
		  }
      Angle_Resolve(&Angle); // 解析角度数据
    }

		USART1_Receive_DMA_Init();
	}
	else if (huart->Instance == USART2)
	{
		if (size <= RC_DMA_RX_BUF_LEN && RC_Cal_Flag == 0)
		{
			for (uint16_t i = 0U; i < size; i++)
			{
				RC_InputByte(rc_dma_rx_buf[i]);
			}
		}

		USART2_Receive_DMA_Init();
	}

}

void HAL_UART_ErrorCallback(UART_HandleTypeDef *huart)
{
  if (huart->Instance == USART1) {
    USART1_Receive_DMA_Init();
  }
  else if (huart->Instance == USART2) {
    USART2_Receive_DMA_Init();
  }
}

